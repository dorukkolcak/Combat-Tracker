	/*
	Length explanation for this builder function:
	I initially just initialized the map styles in the unordered map's constructor.
	Upon doing this I got a compiler warning stating that the size of the unordered map might be "too big" for the stack size.
	I got confused with this as unordered map's data members are heap allocated, not stack allocated.
	Turns out while initializing the static unordered map, all the lambdas used 
	which are inheritently functor objects with specific types) are stack allocated at a single frame.
	So in other words the initializer list argument for the constructor itself is very large for the stack.
	The way we solve this is to define a builder function that emplaces back elements one by one 
	So that only one stack frame at a time is allocated per lambda, initializer list argument and the return value.
	*/
